// PreToolUse hook — blocks edits to files agents must never touch (.env*, ios/, android/, the
// review stamp) and new screen/primitive files without the `// Design:` note (CHILL-001 AC-3, AC-14).
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';

import {
  appliesTo as needsDesignNote,
  checkDesignNote,
  readBoards,
} from '../check-design-source.mjs';
import { isEnvFile } from '../check-secrets.mjs';
import { REPO_ROOT, isMain } from '../lib/gate.mjs';
import { repoRelative, runHook } from './lib.mjs';

export const FILE_TOOLS = new Set(['Write', 'Edit', 'MultiEdit', 'NotebookEdit']);

/** Files no agent may write, with the reason and the right alternative. */
export function protectedReason(file) {
  if (isEnvFile(file)) {
    return `${file} holds local secrets and is never written by an agent — list variable names in .env.example; the owner fills .env.local by hand`;
  }
  if (/^(ios|android)(\/|$)/.test(file)) {
    return `${file} is generated by Expo prebuild (Continuous Native Generation) — change app.json or a config plugin instead`;
  }
  if (/^\.review(\/|$)/.test(file)) {
    return `${file} is written only by \`pnpm review:stamp\` after /review passes — run /review`;
  }
  return null;
}

/** The file's text after the tool runs, for Write / Edit / MultiEdit; null when unknown. */
export function contentAfter(toolName, input, current) {
  if (toolName === 'Write') return input.content ?? '';
  const edits =
    toolName === 'MultiEdit' ? (input.edits ?? []) : toolName === 'Edit' ? [input] : null;
  if (!edits || current === null) return null;
  let text = current;
  for (const edit of edits) {
    if (typeof edit.old_string !== 'string' || typeof edit.new_string !== 'string') return null;
    text = edit.replace_all
      ? text.split(edit.old_string).join(edit.new_string)
      : text.replace(edit.old_string, () => edit.new_string);
  }
  return text;
}

/** Pure decision: returns `{ exitCode, stderr? }` — exit 2 blocks the tool call. */
export function decidePreToolUse(event, { root = REPO_ROOT, readFile, boards } = {}) {
  if (!FILE_TOOLS.has(event.tool_name)) return { exitCode: 0 };
  const input = event.tool_input ?? {};
  const file = repoRelative(input.file_path ?? input.notebook_path, root);
  if (!file) return { exitCode: 0 };

  const reason = protectedReason(file);
  if (reason) return { exitCode: 2, stderr: `Blocked: ${reason}\n` };

  if (needsDesignNote(file)) {
    const after = contentAfter(event.tool_name, input, readFile(file));
    if (after !== null) {
      const violation = checkDesignNote({ path: file, text: after }, boards());
      if (violation) {
        return {
          exitCode: 2,
          stderr: `Blocked by check:design-source: ${file} — ${violation.message}. Fix: ${violation.fix}\n`,
        };
      }
    }
  }
  return { exitCode: 0 };
}

if (isMain(import.meta.url)) {
  await runHook('pre-tool-use', (event) => {
    const root =
      event.cwd && existsSync(path.join(event.cwd, 'package.json')) ? event.cwd : REPO_ROOT;
    return decidePreToolUse(event, {
      root,
      readFile: (file) => {
        const absolute = path.join(root, file);
        return existsSync(absolute) ? readFileSync(absolute, 'utf8') : null;
      },
      boards: () => readBoards({ cwd: root }),
    });
  });
}
